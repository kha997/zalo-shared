// Turn the one-shot reconciliation driver's sanitized JSON into the committed
// evidence report and the gate token. It reads only the driver's own output;
// it never contacts the database or the API.
import { readFileSync, writeFileSync } from "node:fs";

const [resultFile, outFile] = process.argv.slice(2);
if (!resultFile || !outFile) {
  process.stderr.write("reconcile-report: FAIL result and output paths are required\n");
  process.exit(3);
}

let report;
try {
  report = JSON.parse(readFileSync(resultFile, "utf8"));
} catch {
  report = { ok: false, outcome: "no-result", checks: [] };
}

const pass = report.ok === true && (report.outcome === "reconciled" || report.outcome === "reconciled-after-unknown-response");
const blocked = ["outside-window", "precondition-failed", "not-applied"].includes(report.outcome);
const token = pass
  ? "G5A_RECONCILIATION_PASS_AWAITING_BOOTSTRAP_DECISION"
  : blocked
    ? "G5A_RECONCILIATION_BLOCKED"
    : "G5A_RECONCILIATION_FAIL_FENCED";

const cell = (value) => (value === undefined || value === null ? "`null`" : String(value).replace(/\|/g, "\\|"));
const table = (rows) =>
  ["| Field | Value |", "| --- | --- |", ...rows.map(([key, value]) => `| ${key} | ${cell(value)} |`)].join("\n");
const pre = report.preState ?? {};
const post = report.postState ?? {};
const o = pre.control ?? {};
const po = post.control ?? {};
const pc = pre.counts ?? {};
const poc = post.counts ?? {};
const checks = Array.isArray(report.checks) ? report.checks : [];

const lines = [];
lines.push("# G5-A — Controlled reconciliation execution");
lines.push("");
lines.push(`**Date:** ${new Date().toISOString()}`);
lines.push("**Authorization:** the Owner's reconciliation execution authorization");
lines.push("**Authorized window:** `2026-11-05T02:00:00Z`–`2026-11-05T02:20:00Z` (UTC)");
lines.push(`**Verdict:** **\`${token}\`**`);
lines.push(`**Request id:** \`${cell(report.requestId)}\``);
lines.push(`**Evidence reference:** \`${cell(report.evidenceRef)}\``);
lines.push("");
lines.push("Generated by `ops/local/reconcile-pilot.sh execute` from the driver's");
lines.push("sanitized output. One authenticated request at most; no retry, no replay,");
lines.push("no direct database override, no provider communication.");
lines.push("");
lines.push("## 1. Pre-state (read-only)");
lines.push("");
lines.push(
  table([
    ["Database / TLS", `${cell(report.identity?.database ?? "unavailable")} / ssl=${cell(report.identity?.ssl)}`],
    ["`connector_ownership.phase`", o.phase],
    ["`owner_id`", o.owner_id],
    ["`epoch`", o.epoch],
    ["`owner_label` / `fault_code`", `${cell(o.owner_label)} / ${cell(o.fault_code)}`],
    ["`uncertain_at`", o.uncertain_at],
    ["`provider_state.status`", o.status],
    ["`reconciliation_required`", o.reconciliation_required],
    ["`gap_version`", o.gap_version],
    ["users / admins / sessions", `${cell(pc.users)} / ${cell(pc.admins)} / ${cell(pc.sessions)}`],
    ["unresolved events / media / dispatchable / parts", `${cell(pre.unresolved?.events)} / ${cell(pre.unresolved?.media)} / ${cell(pre.unresolved?.dispatchable)} / ${cell(pre.unresolved?.parts)}`],
    ["messages / outbox / delivery parts / provider events", `${cell(pc.messages)} / ${cell(pc.outbox)} / ${cell(pc.delivery_parts)} / ${cell(pc.provider_events)}`],
    ["advisory locks / other active sessions", `${cell(pre.concurrency?.advisory_locks)} / ${cell(pre.concurrency?.other_active_sessions ?? pre.concurrency?.other_sessions)}`],
    ["prior audit rows for this request", pre.priorReconcileRows],
  ]),
);
lines.push("");
lines.push("## 2. Transaction");
lines.push("");
lines.push(
  table([
    ["Outcome", report.outcome],
    ["HTTP status of the single request", report.responseStatus],
    ["Expected owner / epoch / gap", `${cell(report.expected?.ownerId)} / ${cell(report.expected?.epoch)} / ${cell(report.expected?.gapVersion)}`],
    ["Applied epoch / gap", `${cell(report.response?.epoch ?? po.epoch)} / ${cell(report.response?.gapVersion ?? po.gap_version)}`],
    ["Idempotent replay performed", "no"],
    ["Retry performed", "no"],
  ]),
);
if (report.reason) {
  lines.push("");
  lines.push(`**Failure reason:** ${cell(report.reason)}`);
}
lines.push("");
lines.push("## 3. Post-state (separate read-only connection)");
lines.push("");
lines.push(
  table([
    ["`connector_ownership.phase`", po.phase],
    ["`owner_id` / `owner_label`", `${cell(po.owner_id)} / ${cell(po.owner_label)}`],
    ["`epoch`", po.epoch],
    ["`fault_code` / `uncertain_at`", `${cell(po.fault_code)} / ${cell(po.uncertain_at)}`],
    ["`last_fenced_owner_id` / `last_fenced_epoch`", `${cell(po.last_fenced_owner_id)} / ${cell(po.last_fenced_epoch)}`],
    ["`last_fenced_at`", po.last_fenced_at],
    ["`provider_state.status`", po.status],
    ["`reconciliation_required`", po.reconciliation_required],
    ["`gap_version`", po.gap_version],
    ["`provider_state.fault_code`", po.provider_fault],
    ["users / admins / sessions", `${cell(poc.users)} / ${cell(poc.admins)} / ${cell(poc.sessions)}`],
    ["messages / outbox / delivery parts / provider events", `${cell(poc.messages)} / ${cell(poc.outbox)} / ${cell(poc.delivery_parts)} / ${cell(poc.provider_events)}`],
    ["`connector.reconciled` rows for this request", post.reconciledRows],
    ["advisory locks / other active sessions", `${cell(post.concurrency?.advisory_locks)} / ${cell(post.concurrency?.other_active_sessions ?? post.concurrency?.other_sessions)}`],
  ]),
);
lines.push("");
lines.push("## 4. Checks");
lines.push("");
lines.push(
  ["| Check | Result | Detail |", "| --- | --- | --- |", ...checks.map((entry) => {
    const { name, pass: ok, ...detail } = entry;
    const brief = Object.entries(detail)
      .map(([key, value]) => `${key}=${typeof value === "object" ? JSON.stringify(value) : String(value)}`)
      .join("; ")
      .slice(0, 400);
    return `| ${cell(name)} | ${ok ? "PASS" : "FAIL"} | ${cell(brief)} |`;
  })].join("\n"),
);
lines.push("");
lines.push("## 5. Non-actions and provenance");
lines.push("");
lines.push("- No Zalo QR, login or provider network call; the gateway stayed `exited`.");
lines.push("- No observe or send-test, no reconnect, no delivery or unknown-work replay.");
lines.push("- No allowlist change, no deployment, no PR merge, no direct SQL update of any control row.");
lines.push("- The driver's full sanitized JSON was written to the private `pilot-admin` directory with mode `0600`.");
lines.push("- The credential never appeared in this report, in stdout or in the repository.");
lines.push("");
lines.push("## 6. Next step");
lines.push("");
if (pass) {
  lines.push("The fenced incident is reconciled and the pilot is `idle` with epoch and gap advanced");
  lines.push("monotonically. Any G5-A bootstrap requires a new Owner authorization naming a fresh");
  lines.push("UTC window; the 2026-11-04 authorization remains consumed.");
} else {
  lines.push("No bootstrap, retry or manual control-row change is permitted. The Owner must decide");
  lines.push("the next step from this verdict; a new attempt needs a fresh authorization.");
}
lines.push("");

writeFileSync(outFile, lines.join("\n"), { mode: 0o644 });
process.stdout.write(
  `${JSON.stringify({ token, outcome: report.outcome, ok: pass, report: outFile })}\n`,
);
process.exitCode = pass ? 0 : blocked ? 2 : 1;
